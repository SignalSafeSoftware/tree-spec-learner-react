function escapeXml(value) {
    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&apos;");
}

function wrapText(value, maxCharacters) {
    const words = String(value).split(/\s+/u).filter(Boolean);
    const lines = [];
    let current = "";
    for (const word of words) {
        const candidate = current ? `${current} ${word}` : word;
        if (current && candidate.length > maxCharacters) {
            lines.push(current);
            current = word;
        } else {
            current = candidate;
        }
    }
    if (current) lines.push(current);
    return lines;
}

function textLine(x, y, value, attributes = "") {
    return `<text x="${x}" y="${y}" ${attributes}>${escapeXml(value)}</text>`;
}

function renderLines(x, y, lines, lineHeight, attributes = "") {
    return lines
        .map((line, index) => textLine(x, y + index * lineHeight, line, attributes))
        .join("");
}

function nodeFor(spec, nodeId) {
    const node = spec.nodes[nodeId];
    if (!node) throw new Error(`Missing example node '${nodeId}'.`);
    return node;
}

function renderFlowNode(spec, nodeId, layout) {
    const node = nodeFor(spec, nodeId);
    const choices = (node.choices ?? []).slice(0, 2);
    const promptLines = wrapText(node.prompt ?? "", layout.width > 270 ? 36 : 31).slice(0, 2);
    const type = String(node.type ?? "prompt").toUpperCase();
    const typeWidth = type === "PROMPT" ? 84 : 68;
    const promptY = layout.y + 78;
    const choicesY = layout.y + 135;

    return `
      <g filter="url(#shadow)" font-family="${FONT_STACK}">
        <rect x="${layout.x}" y="${layout.y}" width="${layout.width}" height="${layout.height}" rx="10" fill="#ffffff" stroke="#dee2e6" />
        <rect x="${layout.x + 16}" y="${layout.y + 14}" width="${typeWidth}" height="23" rx="5" fill="#0d6efd" />
        ${textLine(layout.x + 16 + typeWidth / 2, layout.y + 30, type, 'text-anchor="middle" fill="#ffffff" font-size="12" font-weight="700"')}
        ${textLine(layout.x + layout.width - 15, layout.y + 30, `Node: ${nodeId}`, 'text-anchor="end" fill="#6c757d" font-size="12"')}
        <line x1="${layout.x}" y1="${layout.y + 48}" x2="${layout.x + layout.width}" y2="${layout.y + 48}" stroke="#dee2e6" />
        ${renderLines(layout.x + 20, promptY, promptLines, 22, 'fill="#212529" font-size="15" font-weight="600"')}
        ${choices.map((choice, index) => {
            const choiceY = choicesY + index * 43;
            const choiceLines = wrapText(choice.label, layout.width > 270 ? 38 : 31).slice(0, 1);
            return `${textLine(layout.x + 20, choiceY, choice.id, 'fill="#6c757d" font-size="12"')}${renderLines(layout.x + 20, choiceY + 20, choiceLines, 18, 'fill="#212529" font-size="13"')}`;
        }).join("")}
      </g>`;
}

function renderOutcome(transition) {
    const outcome = String(transition.outcome ?? "unknown");
    const layout = OUTCOME_LAYOUT[outcome];
    if (!layout) throw new Error(`Missing outcome layout for '${outcome}'.`);
    const title = `END · ${outcome.replaceAll("_", " ").toUpperCase()}`;
    const color = outcome === "safe" ? "#198754" : outcome === "at_risk" ? "#946200" : "#dc3545";
    const background = outcome === "safe" ? "#effcf6" : outcome === "at_risk" ? "#fff8e1" : "#fff5f5";
    return `
      <g filter="url(#shadow)" font-family="${FONT_STACK}">
        <rect x="${layout.x}" y="${layout.y}" width="${layout.width}" height="${layout.height}" rx="10" fill="${background}" stroke="${color}" />
        ${textLine(layout.x + 20, layout.y + 29, title, `fill="${color}" font-size="12" font-weight="700"`)}
        ${textLine(layout.x + 20, layout.y + 53, OUTCOME_DESCRIPTIONS[outcome] ?? "Terminal outcome", 'fill="#495057" font-size="12"')}
      </g>`;
}

function renderTransition(spec, transition) {
    const [fromNodeId, choiceId] = transition.from;
    const fromLayout = FLOW_LAYOUT[fromNodeId];
    if (!fromLayout) throw new Error(`Missing node layout for '${fromNodeId}'.`);
    const choiceIndex = nodeFor(spec, fromNodeId).choices.findIndex((choice) => choice.id === choiceId);
    const startX = fromLayout.x + fromLayout.width;
    const startY = fromLayout.y + 85 + Math.max(choiceIndex, 0) * 38;
    const isTerminal = transition.to === END_NODE_ID;
    const targetLayout = isTerminal ? OUTCOME_LAYOUT[String(transition.outcome)] : FLOW_LAYOUT[transition.to];
    if (!targetLayout) throw new Error(`Missing target layout for '${transition.to}'.`);
    const endX = isTerminal ? targetLayout.x + targetLayout.width / 2 : targetLayout.x;
    const endY = isTerminal ? targetLayout.y : targetLayout.y + targetLayout.height / 2;
    const controlX = (startX + endX) / 2;
    const labelX = (startX + endX) / 2;
    const labelY = (startY + endY) / 2 - 8;
    return `
      <path d="M ${startX} ${startY} C ${controlX} ${startY}, ${controlX} ${endY}, ${endX} ${endY}" fill="none" stroke="#6c757d" stroke-width="2" marker-end="url(#arrow)" />
      ${textLine(labelX, labelY, choiceId, 'text-anchor="middle" fill="#495057" font-size="12" font-weight="600"')}`;
}

function renderFlowImage(spec) {
    const transitions = spec.transitions.map((transition) => renderTransition(spec, transition));
    const terminalTransitions = spec.transitions.filter((transition) => transition.to === END_NODE_ID);
    const outcomes = terminalTransitions.map((transition) => renderOutcome(transition)).join("");
    const nodes = Object.entries(FLOW_LAYOUT)
        .map(([nodeId, layout]) => renderFlowNode(spec, nodeId, layout))
        .join("");
    return `<?xml version="1.0" encoding="UTF-8"?>
${GENERATED_HEADER}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1120 560" role="img" aria-labelledby="title desc">
  <title id="title">TreeSpec incident response example flow</title>
  <desc id="desc">A branching TreeSpec flow generated from the documentation example data.</desc>
  <defs>
    <marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M 0 0 L 10 5 L 0 10 z" fill="#6c757d" /></marker>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="130%"><feDropShadow dx="0" dy="3" stdDeviation="4" flood-color="#172b4d" flood-opacity="0.12" /></filter>
  </defs>
  <rect width="1120" height="560" fill="#f5f7fa" />
  ${textLine(40, 42, "TreeSpec example flow", `fill="#212529" font-family="${FONT_STACK}" font-size="25" font-weight="700"`)}
  ${textLine(40, 68, "Generated from the live incident-response TreeSpec example", `fill="#6c757d" font-family="${FONT_STACK}" font-size="14"`)}
  <g font-family="${FONT_STACK}">${transitions.join("")}</g>
  ${nodes}
  ${outcomes}
  ${textLine(40, 540, "Nodes expose prompts and choices; transitions determine the next node or terminal outcome.", `fill="#6c757d" font-family="${FONT_STACK}" font-size="12"`)}
</svg>
`;
}

function renderHtmlImage(width, height, title, description, styles, markup) {
    return `<?xml version="1.0" encoding="UTF-8"?>
${GENERATED_HEADER}
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title desc">
  <title id="title">${escapeXml(title)}</title>
  <desc id="desc">${escapeXml(description)}</desc>
  <foreignObject x="0" y="0" width="${width}" height="${height}">
    <div xmlns="http://www.w3.org/1999/xhtml">
      <style>${styles}</style>
      ${markup}
    </div>
  </foreignObject>
</svg>
`;
}

function renderLearnerImage(spec) {
    const session = createInitialTreeSpecSession(spec);
    const node = getTreeSpecNodeView(session.spec, session.currentNodeId);
    const decisionMarkup = renderToStaticMarkup(React.createElement(TreeSpecDecisionView, {
        node,
        caption: "What would you do?",
        onChoice: () => undefined,
    }));
    const markup = `
      <main class="preview-page">
        <h1>Learner-facing TreeSpecDecisionView</h1>
        <p class="subtitle">Current node: ${escapeXml(node.id)} · rendered from the exported package component</p>
        <section class="dp-card">
          <header class="dp-card__header"><span class="badge">Prompt</span><span class="node-id">Node: ${escapeXml(node.id)}</span></header>
          <div class="dp-card__body">${decisionMarkup}</div>
        </section>
        <p class="note">Generated with the public TreeSpecDecisionView export and the current node returned by simulator-core.</p>
      </main>`;
    return renderHtmlImage(1040, 690, "TreeSpec learner decision view", "A learner-facing decision view generated by rendering the exported React component.", LEARNER_STYLES, markup);
}

function toDecisionFeedback(feedback) {
    if (!feedback || typeof feedback !== "object") return null;
    return {
        title: feedback.title,
        body: feedback.body,
        redFlags: feedback.red_flags,
        takeaway: feedback.takeaway,
    };
}

function renderFeedbackImage(spec) {
    const session = createInitialTreeSpecSession(spec);
    const result = dispatchTreeSpecChoice(session, spec.start_node, learnerChoiceId);
    const feedback = toDecisionFeedback(result.feedback);
    if (!feedback) throw new Error("The example choice did not produce feedback.");
    const toastMarkup = renderToStaticMarkup(React.createElement(DecisionFeedbackToast, {
        feedback,
        onClose: () => undefined,
        className: "preview-toast",
    }));
    const markup = `
      <main class="preview-page">
        <h1>TreeSpec decision feedback</h1>
        <p class="subtitle">Feedback returned by simulator-core after the “${escapeXml(learnerChoiceId)}” choice</p>
        ${toastMarkup}
        <p class="note">Generated with the public DecisionFeedbackToast export and live transition feedback.</p>
      </main>`;
    return renderHtmlImage(620, 300, "TreeSpec decision feedback toast", "A feedback toast generated by rendering the exported React component.", TOAST_STYLES, markup);
}

const artifacts = new Map([
    ["tree-spec-example-flow.svg", renderFlowImage(incidentResponseTreeSpec)],
    ["tree-spec-learner-view.svg", renderLearnerImage(incidentResponseTreeSpec)],
    ["tree-spec-feedback-toast.svg", renderFeedbackImage(incidentResponseTreeSpec)],
]);

const checkOnly = process.argv.includes("--check");
for (const [filename, content] of artifacts) {
    const outputPath = path.join(DOCS_DIRECTORY, "..", filename);
    if (checkOnly) {
        const existing = fs.readFileSync(outputPath, "utf8");
        if (existing !== content) {
            throw new Error(`${filename} is stale; run yarn docs:images.`);
        }
    } else {
        fs.writeFileSync(outputPath, content, "utf8");
    }
}

console.log(`${checkOnly ? "Verified" : "Generated"} ${artifacts.size} documentation images from public learner components.`);
